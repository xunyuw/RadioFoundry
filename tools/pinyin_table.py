"""Build the pinyin input method's tables from pypinyin.

A radio keypad types Latin letters; a Chinese name needs a way from letters to characters. This tool writes the two
tables the editor searches (core/ui/pinyin_data.c):

  pinyin_syllable[]   every distinct reading, sorted, 8 bytes each: "zhuang" and a NUL, zero padded
  pinyin_entry[]      one per character that has a reading, sorted by (syllable, codepoint): the code point (2 B) and
                      the syllable index (2 B)

The search is a prefix binary search over pinyin_syllable, then a walk of pinyin_entry: type "zh" and the candidates
are every character whose reading starts with "zh", in syllable order. Punctuation and symbols have no reading and are
not in the table (the editor lists them another way).

    tools/pinyin_table.py --out-c core/ui/pinyin_data.c

pypinyin is a build-time tool only: it carries the readings, not the firmware.
"""
import argparse
import collections
import os
import unicodedata

from pypinyin import Style, pinyin

SYLLABLE_BYTES = 8		# the longest reading is "zhuang" (6) plus a NUL, padded to 8


def gb2312_chars():
    """Every character GB2312 codes, in code point order: the set the face covers (tools/cjkfont.py --gb2312)."""
    out = set()
    for hb in range(0xA1, 0xFF):
        for lb in range(0xA1, 0xFF):
            try:
                ch = bytes([hb, lb]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1 and ord(ch) > 0x7E and not ch.isspace():
                out.add(ch)
    return sorted(out, key=ord)


def reading(ch):
    """The character's pinyin without its tone, lower case, or None when it has no reading (a symbol)."""
    cat = unicodedata.category(ch)
    if cat[0] in ("P", "S", "Z"):
        return None
    try:
        py = pinyin(ch, style=Style.NORMAL, errors="ignore")
    except Exception:
        return None
    if not py or not py[0]:
        return None
    s = py[0][0]
    if not s or not s.isascii() or not s.isalpha():
        return None
    return s.lower()


def build(chars):
    by_syllable = collections.defaultdict(list)
    for ch in chars:
        s = reading(ch)
        if s is not None:
            by_syllable[s].append(ch)
    syllables = sorted(by_syllable)
    entries = []				# (codepoint, syllable index), sorted by syllable then code point
    for i, s in enumerate(syllables):
        for ch in sorted(by_syllable[s], key=ord):
            entries.append((ord(ch), i))
    return syllables, entries


def c_bytes(ch):
    return "".join("\\x%02X" % b for b in ch.encode("utf-8"))


def write_c(path, syllables, entries, notice, in_flash=False):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// SPDX-License-Identifier: MIT\n")
        f.write("// Copyright (c) 2026 The RadioFoundry Authors\n")
        f.write("//\n")
        f.write("// Generated by tools/pinyin_table.py; do not edit.\n")
        f.write("// Readings from pypinyin %s (MIT), a build-time tool: no part of it is in the firmware.\n"
                % notice)
        f.write("// %d readings, %d characters (core/ui/pinyin.c)\n" % (len(syllables), len(entries)))
        f.write("\n")
        f.write('#include "pinyin.h"\n\n')
        f.write("#if CONFIG_PINYIN\n")
        f.write("const uint16_t pinyin_syllable_count = %d;\n\n" % len(syllables))
        f.write("const uint16_t pinyin_entry_count = %d;\n\n" % len(entries))
        if in_flash:
            # The tables are in the data flash at CONFIG_PINYIN_ADDR; --out-bin wrote them there
            f.write("// The tables live in the data flash (CONFIG_PINYIN_ADDR)\n")
            f.write("const uint32_t pinyin_addr = CONFIG_PINYIN_ADDR;\n")
        else:
            f.write("const char pinyin_syllable[][PINYIN_SYLLABLE_BYTES] = {\n")
            for s in syllables:
                f.write('\t"%s",\n' % s)
            f.write("};\n\n")
            f.write("// Sorted by reading, then by code point: a prefix search becomes one walk\n")
            f.write("const pinyin_entry_t pinyin_entry[] = {\n")
            for cp, si in entries:
                f.write("\t{ 0x%04X, %d },\t/* %s */\n" % (cp, si, c_bytes(chr(cp))))
            f.write("};\n\n")
        f.write("#endif\n")


def write_bin(path, syllables, entries):
    """The two tables as one binary for the data flash, in the order the search reads them: every reading field first,
    then the entries. Both are 2-byte aligned, so no padding is needed between them."""
    blob = bytearray()
    for s in syllables:
        field = s.encode("ascii")[:SYLLABLE_BYTES - 1]
        blob += field + b"\0" * (SYLLABLE_BYTES - len(field))
    for cp, si in entries:
        blob += cp.to_bytes(2, "little") + si.to_bytes(2, "little")
    pad = (-len(blob)) % 0x1000
    blob += b"\xff" * pad
    with open(path, "wb") as f:
        f.write(blob)
    return len(blob)


def main():
    ap = argparse.ArgumentParser(description="Build the pinyin input method's tables (docs/dev/translating.md)")
    ap.add_argument("--out-c", required=True, help="the C file to write")
    ap.add_argument("--out-bin", help="write the tables as a binary for the data flash instead of in the C file "
                    "(the C file then carries only their counts and address, core/ui/pinyin.c reads them there)")
    ap.add_argument("--names", help="also report the readings for this file's characters (a checks file)")
    args = ap.parse_args()

    chars = gb2312_chars()
    syllables, entries = build(chars)
    if not syllables:
        raise SystemExit("pinyin_table: pypinyin gave no readings: is it installed? (pip install pypinyin)")
    import pypinyin
    write_c(args.out_c, syllables, entries, getattr(pypinyin, "__version__", "?"), in_flash=args.out_bin is not None)
    if args.out_bin:
        n = write_bin(args.out_bin, syllables, entries)
        print("  %s holds the tables in %d bytes, padded to whole 4 KB sectors" % (args.out_bin, n))
    print("pinyin_table: %d readings, %d characters, %d bytes of table" % (
        len(syllables), len(entries), len(syllables) * SYLLABLE_BYTES + len(entries) * 4))
    print("  the C file is %d bytes" % os.path.getsize(args.out_c))


if __name__ == "__main__":
    main()
